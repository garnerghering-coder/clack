// Manual imports and checks: npm run import -- <gtfs|norway|finland|denmark|denmark-history|denmark-archive|history|observed-backfill|reproject|trv-stations|basemap|logos|bootstrap|audit|position-check> [--force-download] [--reimport] [--zip=path] [--maxzoom=N]
import fs from 'node:fs';
import path from 'node:path';
import { config, REPO_ROOT } from './env.js';
import { openDb } from './db/client.js';
import { bootstrap, refreshTrvStations, runDenmarkImport, runFinlandImport, runGtfsImport, runNorwayImport } from './import/run.js';
import { extractBasemap } from './import/basemap.js';
import { refreshLogos } from './import/logos.js';
import { AUDIT_DIR, runAudit } from './audit/audit.js';
import { backfillSweden } from './import/backfill.js';
import { backfillRange as backfillDenmarkArchive } from './observed/dk-archive.js';
import { importDenmarkHistory } from './import/gtfs-dk-history.js';

const [cmd = 'bootstrap', ...flags] = process.argv.slice(2);
const flag = (name: string) => flags.includes(`--${name}`);
const zip = flags.find((f) => f.startsWith('--zip='))?.slice(6);
const maxZoom = flags.find((f) => f.startsWith('--maxzoom='))?.slice(10);
const db = openDb(config.databasePath);

if (cmd === 'gtfs') {
  const summary = await runGtfsImport(db, { forceDownload: flag('force-download'), reimport: flag('reimport'), zip });
  if (summary?.needsReview.length) console.log(`stations needing review:\n  ${summary.needsReview.join('\n  ')}`);
} else if (cmd === 'norway') {
  await runNorwayImport(db, { forceDownload: flag('force-download'), reimport: flag('reimport') });
} else if (cmd === 'finland') {
  await runFinlandImport(db, { forceDownload: flag('force-download'), reimport: flag('reimport'), zip });
} else if (cmd === 'denmark') {
  await runDenmarkImport(db, { forceDownload: flag('force-download'), reimport: flag('reimport'), zip });
} else if (cmd === 'denmark-archive') {
  // train-archive.eu's finished Danish days (from 2026-09-30): [--from=YYYY-MM-DD] [--to=YYYY-MM-DD].
  await backfillDenmarkArchive(db, { from: flags.find((f) => f.startsWith('--from='))?.slice(7), to: flags.find((f) => f.startsWith('--to='))?.slice(5) });
} else if (cmd === 'denmark-history') {
  // Old Danish timetables from the Mobility Database: [--limit=N] copies this run.
  const limit = flags.find((f) => f.startsWith('--limit='))?.slice(8);
  await importDenmarkHistory(db, { limit: limit ? Number(limit) : undefined });
} else if (cmd === 'art-needed') {
  const { artNeeded } = await import('./tools/artNeeded.js');
  const date = flags.find((f) => f.startsWith('--date='))?.slice(7) ?? '2026-10-28';
  const out = path.join(REPO_ROOT, 'docs/TRAIN_ART_NEEDED.md');
  fs.writeFileSync(out, artNeeded(db, date));
  console.log(`wrote ${out}`);
} else if (cmd === 'position-check') {
  // The positioning numbers (docs/POSITIONING.md): [--minutes=N] listening here, or [--server=URL --admin=TOKEN] from a running server.
  const { positionCheck } = await import('./tools/positionCheck.js');
  const minutes = Number(flags.find((f) => f.startsWith('--minutes='))?.slice(10)) || undefined;
  const server = flags.find((f) => f.startsWith('--server='))?.slice(9);
  const admin = flags.find((f) => f.startsWith('--admin='))?.slice(8) ?? process.env.CLACK_ADMIN_TOKEN;
  const { markdown } = await positionCheck(db, { minutes, server, admin, log: (m) => console.error(m) });
  console.log(markdown);
} else if (cmd === 'station-tiers') {
  const { stationTiers } = await import('./tools/stationTiers.js');
  const date = flags.find((f) => f.startsWith('--date='))?.slice(7) ?? '2026-10-28';
  const res = await stationTiers(db, date);
  const file = {
    _comment: 'Station tiers for the change rule (packages/shared/src/changes.ts): hub 15 min, mid 10, default 7. Generated by `npm run import -- station-tiers` from the timetable for `date` (commuter trains left out); counts per station are the source (apps/server/src/tools/stationTiers.ts). Only hub and mid stations are listed; any other station is default. `review` marks stations where the three rules disagree, for the owner to check.',
    date: res.date,
    stations: Object.fromEntries(res.stations.filter((s) => s.tier !== 'default').map(({ id, ...rest }) => [id, rest])),
  };
  fs.writeFileSync(path.join(REPO_ROOT, 'data/station_tiers.json'), JSON.stringify(file, null, 1) + '\n');
  const c = (t: string) => res.stations.filter((s) => s.tier === t).length;
  console.log(`hubs ${c('hub')}, mid ${c('mid')}, review ${res.stations.filter((s) => s.review && s.tier !== 'default').length}`);
} else if (cmd === 'history') {
  // Sweden's past timetables ahead of time: --from=YYYY-MM-DD [--to=YYYY-MM-DD] (to: the day before the current feed).
  const from = flags.find((f) => f.startsWith('--from='))?.slice(7);
  if (!from) throw new Error('history needs --from=YYYY-MM-DD');
  await backfillSweden(db, { from, to: flags.find((f) => f.startsWith('--to='))?.slice(5) });
} else if (cmd === 'observed-backfill') {
  // The observed record's past, fast: --country=NO|FI --from=YYYY-MM-DD [--to=…] [--parallel=N].
  const country = flags.find((f) => f.startsWith('--country='))?.slice(10);
  const from = flags.find((f) => f.startsWith('--from='))?.slice(7);
  const to = flags.find((f) => f.startsWith('--to='))?.slice(5);
  const parallel = Number(flags.find((f) => f.startsWith('--parallel='))?.slice(11)) || undefined;
  if (!from || (country !== 'NO' && country !== 'FI')) throw new Error('observed-backfill needs --country=NO|FI and --from=YYYY-MM-DD');
  const mod = country === 'NO' ? await import('./observed/bigquery.js') : await import('./observed/finland.js');
  await mod.backfillRange(db, { from, to, parallel });
} else if (cmd === 'reproject') {
  // Rebuild the observed record's Norwegian archive days from the raw files (after a change to how they're read).
  const { reproject } = await import('./observed/bigquery.js');
  await reproject(db, { log: console.log });
} else if (cmd === 'trv-stations') {
  await refreshTrvStations(db);
} else if (cmd === 'basemap') {
  await extractBasemap({ maxZoom: maxZoom ? Number(maxZoom) : undefined, out: flags.find((f) => f.startsWith('--out='))?.slice(6) });
} else if (cmd === 'logos') {
  await refreshLogos(console.log, { force: flag('force') });
} else if (cmd === 'bootstrap') {
  await bootstrap(db);
} else if (cmd === 'audit') {
  const r = await runAudit(db, { log: console.log });
  console.log(`audited ${r.audited} new trip(s); report: ${AUDIT_DIR}/latest.md`);
} else {
  console.error(`unknown command "${cmd}"; use gtfs | norway | finland | denmark | denmark-history | denmark-archive | history | observed-backfill | reproject | trv-stations | basemap | logos | bootstrap | audit`);
  process.exitCode = 1;
}
