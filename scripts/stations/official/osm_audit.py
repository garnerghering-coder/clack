"""What each station map is missing, as small questions anyone can answer from an operator's page, a photo or a call
(data/stations/OSM_AUDIT.md). Reads the station's cached OpenStreetMap extract (data/cache/stations/<id>-osm.json,
the drafter's; no request is made) and its map, and counts inside the drafter's radius what a walking map is built
from: level tags, steps, lifts, escalators (conveying), indoor areas, entrances. Each gap becomes one question naming
the platform, level or place it is about; an answer is applied to the edits file with its source.

Usage: python3 scripts/stations/official/osm_audit.py            (every map and every hub or mid station)
"""
import json
import math
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
HOURS = {"cafe", "restaurant", "kiosk", "shop", "pharmacy", "waiting"}


def counts(safe, edits, origin):
    path = os.path.join(ROOT, f"data/cache/stations/{safe}-osm.json")
    if not os.path.exists(path) or not origin:
        return None
    osm = json.load(open(path))
    lat0, lon0 = origin
    K = math.cos(math.radians(lat0)) * 111320
    r = edits.get("radius", 400)
    inside = lambda la, lo: math.hypot((lo - lon0) * K, (la - lat0) * 111320) <= r
    c = dict(level=0, steps=0, elevator=0, escalator=0, indoor=0, entrance=0)
    things = list(osm["nodes"].values()) + [w for w in osm["ways"].values()]
    for o in things:
        t = o["t"]
        la, lo = (o["lat"], o["lon"]) if "lat" in o else (o["nd"][0][1], o["nd"][0][2])
        if not inside(la, lo):
            continue
        c["level"] += "level" in t
        c["steps"] += t.get("highway") == "steps" and not t.get("conveying")
        c["elevator"] += t.get("highway") == "elevator"
        c["escalator"] += bool(t.get("conveying"))
        c["indoor"] += "indoor" in t
        c["entrance"] += t.get("railway") == "train_station_entrance" or "entrance" in t
    return c


def questions(m, c):
    q = []
    lv = {l["id"]: l["name"] for l in m["levels"]}
    nodes = {n["id"]: n for n in m["nodes"]}
    for p in m["platforms"]:
        if p.get("unconnected"):
            q.append(f"How do you get to platform {p['ref']} (tracks {', '.join(p['tracks'])})? Stairs, a lift or a path, and from which hall or street?")
    vertical_levels = {nodes[e[k]]["level"] for e in m["edges"] if e["kind"] != "walk" for k in ("from", "to") if e[k] in nodes}
    if len(m["levels"]) > 1:
        for l in m["levels"]:
            if l["id"] not in vertical_levels:
                q.append(f"Which stairs, escalators or lifts lead to “{l['name']}”, and from where?")
            # The platforms' level is the reference (0 m) by definition.
            if l.get("height_m") is None and l["id"] not in {p["level"] for p in m["platforms"]}:
                q.append(f"How far above or below the platforms is “{l['name']}” (metres, or the number of flights)?")
    for p in m["platforms"]:
        edges = p.get("edges") or []
        if len(p["tracks"]) > 1 and (not edges or any(e.get("track") is None for e in edges) or len({e.get('track') for e in edges}) < len(p["tracks"])):
            q.append(f"Platform {p['ref']}: which track is on which side (a photo of the signs, or the station's plan)?")
    if not any(n["type"] == "entrance" for n in m["nodes"]) or all("footway end" in (n.get("_source") or "") for n in m["nodes"] if n["type"] == "entrance"):
        q.append("Where are the station's entrances (each door or street exit, and the floor it is on)?")
    no_hours = [x for x in m["pois"] if x["category"] in HOURS and not x.get("opening_hours")]
    if no_hours:
        q.append(f"Opening hours of {', '.join(sorted({x['name'] or x['category'] for x in no_hours})[:6])}{' and others' if len(no_hours) > 6 else ''} (the shop's or the station's page)")
    if c is not None:
        if len(m["levels"]) > 1 and c["steps"] + c["elevator"] + c["escalator"] == 0:
            q.append("OpenStreetMap has no stairs, lifts or escalators here: a plan of the station (the operator's) would give them all.")
        if c["level"] == 0 and len(m["platforms"]) > 2:
            q.append("OpenStreetMap has no floor (level) tags here: is everything on one floor, or is there a tunnel or a bridge to the platforms?")
    return q


def main():
    tiers = json.load(open(os.path.join(ROOT, "data/station_tiers.json")))["stations"]
    sdir = os.path.join(ROOT, "data/stations")
    maps = {}
    for f in os.listdir(sdir):
        if f.endswith(".json"):
            m = json.load(open(os.path.join(sdir, f)))
            maps[m["station_id"]] = m
    ids = sorted(set(maps) | set(tiers), key=lambda i: -(tiers.get(i, {}).get("trains") or 0))
    out = ["# Station maps: questions for the missing facts", "",
           "Generated by `python3 scripts/stations/official/osm_audit.py`. Per station, busiest first (trains a day from "
           "data/station_tiers.json), what its map is missing, as questions anyone can answer from the operator's page, a "
           "photo or a call. Each answer goes into the station's edits file with its source. Counts are OpenStreetMap "
           "objects inside the drafter's radius.", ""]
    asked = 0
    for sid in ids:
        safe = sid.replace(":", "_")
        m = maps.get(sid)
        epath = os.path.join(ROOT, f"scripts/stations/{safe}.edits.json")
        edits = json.load(open(epath)) if os.path.exists(epath) else {}
        name = (m or {}).get("name") or tiers.get(sid, {}).get("name") or sid
        tier = tiers.get(sid, {}).get("tier", "–")
        if not m:
            out += [f"## {name} (`{sid}`, {tier})", "", "- No map yet: the batch drafts one when OpenStreetMap has numbered platforms here.", ""]
            continue
        c = counts(safe, edits, (m["origin"]["lat"], m["origin"]["lon"]))
        qs = questions(m, c)
        asked += len(qs)
        head = f"## {name} (`{sid}`, {tier}, {len(m['platforms'])} platforms, {len(m['levels'])} levels)"
        cnt = f"OSM: {c['level']} with levels, {c['steps']} stairs, {c['elevator']} lifts, {c['escalator']} escalators, {c['indoor']} indoor, {c['entrance']} entrances." if c else "OSM extract not cached."
        out += [head, "", cnt, ""] + ([f"- {x}" for x in qs] or ["- Nothing open."]) + [""]
    open(os.path.join(sdir, "OSM_AUDIT.md"), "w").write("\n".join(out))
    print(f"wrote data/stations/OSM_AUDIT.md: {asked} questions over {len(maps)} maps")


if __name__ == "__main__":
    main()
