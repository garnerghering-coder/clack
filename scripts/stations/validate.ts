// Checks every station map in data/stations (ADDITIONS_01 C; schema 2 in docs/STATION_MAPPING.md). Also runs in
// `npm test` (apps/server/test/stationMaps.test.ts).
// Usage: npm run stations:validate [-- --review]
//   --review  also writes data/stations/REVIEW.md: what each map is still missing (for Garner or a walk), with the
//             tracks the timetable uses at the station when data/app.db is there.
import fs from 'node:fs';
import path from 'node:path';
import { stationReview, validateStationMap, type StationMap } from '../../packages/shared/src/station.ts';

const dir = path.join(import.meta.dirname, '../../data/stations');
const review = process.argv.includes('--review');
let bad = 0;
const queue: string[] = ['# Station maps: review queue', '', `Generated by \`npm run stations:validate -- --review\` on ${new Date().toISOString().slice(0, 10)}. Not errors: things a walk, a plan, a video or a photo can settle. See docs/STATION_MAPPING.md.`, ''];

/** Tracks the timetable names at a station (Norway, Finland and Denmark carry platform codes; Sweden's GTFS doesn't). */
function knownTracks(stationId: string): string[] | null {
  const dbFile = path.join(import.meta.dirname, '../../data/app.db');
  if (!fs.existsSync(dbFile)) return null;
  try {
    // Loaded lazily: the validator must still run where better-sqlite3 isn't built.
    const Database = (require as NodeJS.Require)('better-sqlite3') as new (file: string, opts: { readonly: boolean }) => { prepare(sql: string): { all(...args: unknown[]): { p: string }[] } };
    const db = new Database(dbFile, { readonly: true });
    const rows = db.prepare('select distinct platform as p from timetable_stop_times where station_id = ? and platform is not null').all(stationId);
    const obs = db.prepare("select distinct platform as p from observed_calls where station_id = ? and platform is not null and platform <> '' limit 200").all(stationId);
    return [...new Set([...rows, ...obs].map((r) => String(r.p)))];
  } catch {
    return null;
  }
}

for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const m = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')) as StationMap;
  const errors = validateStationMap(m);
  console.log(`${errors.length ? '✗' : '✓'} ${m.name} (${f}, schema ${m.schema ?? 1}): ${m.platforms.length} platforms, ${m.nodes.length} nodes, ${m.edges.length} edges, ${m.pois.length} amenities`);
  for (const e of errors) console.log(`    ${e}`);
  if (errors.length) bad++;
  if (review) {
    const items = stationReview(m, knownTracks(m.station_id));
    queue.push(`## ${m.name} (\`${m.station_id}\`, schema ${m.schema ?? 1}, ${m.quality})`, '', ...(items.length ? items.map((i) => `- ${i}`) : ['- nothing open']), '');
  }
}
if (review) {
  // Platform heights where the laser and Trafikverket's register disagree (the research pass): the maps use the
  // register until a photo, a walk or the operator settles each (owner, 2026-10-30).
  const heights = path.join(dir, 'research', 'REVIEW_platform_heights_SE.md');
  if (fs.existsSync(heights)) {
    const table = fs.readFileSync(heights, 'utf8').split('\n').filter((l) => l.startsWith('|'));
    queue.push('## Platform heights: laser vs Trafikverket\'s register (Sweden)', '', 'The maps use the register\'s class height; each row needs a photo, a walk or the operator to settle. From `research/REVIEW_platform_heights_SE.md`.', '', ...table, '');
  }
  fs.writeFileSync(path.join(dir, 'REVIEW.md'), queue.join('\n'));
  console.log(`wrote ${path.join(dir, 'REVIEW.md')}`);
}
process.exit(bad ? 1 : 0);
