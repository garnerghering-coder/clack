// Checks every station map in data/stations (ADDITIONS_01 C; schema 2 in docs/STATION_MAPPING.md). Also runs in
// `npm test` (apps/server/test/stationMaps.test.ts).
// Usage: npm run stations:validate [-- --review] [-- --coverage]
//   --review    also writes data/stations/REVIEW.md: what each map is still missing (for Garner or a walk), with the
//               tracks the timetable uses at the station when data/app.db is there.
//   --coverage  writes each map's `coverage` (stationCoverage) into its file and data/stations/COVERAGE.md: the scores
//               per station, busiest first (timetable calls when data/app.db is there, else the tier file's trains).
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { stationCoverage, stationReview, validateStationMap, type StationCoverage, type StationMap } from '../../packages/shared/src/station.ts';

const dir = path.join(import.meta.dirname, '../../data/stations');
// better-sqlite3 is the server's dependency: resolve it from there.
const serverRequire = createRequire(path.join(import.meta.dirname, '../../apps/server/package.json'));
const review = process.argv.includes('--review');
const coverage = process.argv.includes('--coverage');
const rows: { m: StationMap; c: StationCoverage; f: string }[] = [];
let bad = 0;
const queue: string[] = ['# Station maps: review queue', '', `Generated by \`npm run stations:validate -- --review\` on ${new Date().toISOString().slice(0, 10)}. Not errors: things a walk, a plan, a video or a photo can settle. See docs/STATION_MAPPING.md.`, ''];

/** Calls at a station in the loaded timetable (a busyness measure for ordering), or null without data/app.db. */
function timetableCalls(stationId: string): number | null {
  const dbFile = path.join(import.meta.dirname, '../../data/app.db');
  if (!fs.existsSync(dbFile)) return null;
  try {
    const Database = serverRequire('better-sqlite3') as new (file: string, opts: { readonly: boolean }) => { prepare(sql: string): { get(...args: unknown[]): { n: number } } };
    return new Database(dbFile, { readonly: true }).prepare('select count(*) as n from timetable_stop_times where station_id = ?').get(stationId).n;
  } catch {
    return null;
  }
}

/** The map file with `coverage` set, edited in place so the rest of the file (the drafter's number format) stays. */
function withCoverage(text: string, c: StationCoverage): string {
  const json = `"coverage":${JSON.stringify(c)}`;
  if (/"coverage":\{[^}]*\}/.test(text)) return text.replace(/"coverage":\{[^}]*\}/, json);
  return text.replace(/("quality":"[a-z_]+")/, `$1,${json}`);
}

/** Tracks the timetable names at a station (Norway, Finland and Denmark carry platform codes; Sweden's GTFS doesn't). */
function knownTracks(stationId: string): string[] | null {
  const dbFile = path.join(import.meta.dirname, '../../data/app.db');
  if (!fs.existsSync(dbFile)) return null;
  try {
    // Loaded lazily: the validator must still run where better-sqlite3 isn't built.
    const Database = serverRequire('better-sqlite3') as new (file: string, opts: { readonly: boolean }) => { prepare(sql: string): { all(...args: unknown[]): { p: string }[] } };
    const db = new Database(dbFile, { readonly: true });
    const rows = db.prepare('select distinct platform as p from timetable_stop_times where station_id = ? and platform is not null').all(stationId);
    const obs = db.prepare("select distinct platform as p from observed_calls where station_id = ? and platform is not null and platform <> '' limit 200").all(stationId);
    return [...new Set([...rows, ...obs].map((r) => String(r.p)))];
  } catch {
    return null;
  }
}

for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const text = fs.readFileSync(path.join(dir, f), 'utf8');
  const m = JSON.parse(text) as StationMap;
  if (coverage) {
    const c = stationCoverage(m);
    rows.push({ m, c, f });
    const next = withCoverage(text, c);
    if (next !== text) fs.writeFileSync(path.join(dir, f), next);
  }
  const errors = validateStationMap(m);
  console.log(`${errors.length ? '✗' : '✓'} ${m.name} (${f}, schema ${m.schema ?? 1}): ${m.platforms.length} platforms, ${m.nodes.length} nodes, ${m.edges.length} edges, ${m.pois.length} amenities`);
  for (const e of errors) console.log(`    ${e}`);
  if (errors.length) bad++;
  if (review) {
    const items = stationReview(m, knownTracks(m.station_id));
    queue.push(`## ${m.name} (\`${m.station_id}\`, schema ${m.schema ?? 1}, ${m.quality})`, '', ...(items.length ? items.map((i) => `- ${i}`) : ['- nothing open']), '');
  }
}
if (review) {
  // Platform heights where the laser and Trafikverket's register disagree (the research pass): the maps use the
  // register until a photo, a walk or the operator settles each (owner, 2026-10-30).
  const heights = path.join(dir, 'research', 'REVIEW_platform_heights_SE.md');
  if (fs.existsSync(heights)) {
    const table = fs.readFileSync(heights, 'utf8').split('\n').filter((l) => l.startsWith('|'));
    queue.push('## Platform heights: laser vs Trafikverket\'s register (Sweden)', '', 'The maps use the register\'s class height; each row needs a photo, a walk or the operator to settle. From `research/REVIEW_platform_heights_SE.md`.', '', ...table, '');
  }
  fs.writeFileSync(path.join(dir, 'REVIEW.md'), queue.join('\n'));
  console.log(`wrote ${path.join(dir, 'REVIEW.md')}`);
}
if (coverage) {
  const tiers = (JSON.parse(fs.readFileSync(path.join(dir, '../station_tiers.json'), 'utf8')) as { stations: Record<string, { tier: string; trains?: number; country: string }> }).stations;
  const busy = new Map(rows.map(({ m }) => [m.station_id, timetableCalls(m.station_id) ?? tiers[m.station_id]?.trains ?? 0]));
  const country = (id: string) => tiers[id]?.country ?? (id.startsWith('74') ? 'SE' : id.startsWith('76') || id.startsWith('NSR') ? 'NO' : id.startsWith('86') ? 'DK' : id.startsWith('fi:') ? 'FI' : '?');
  const pct = (x: number | undefined) => (x === undefined ? '–' : `${Math.round(x * 100)}`);
  const out = ['# Station maps: coverage', '', `Generated by \`npm run stations:validate -- --coverage\` on ${new Date().toISOString().slice(0, 10)}. Per cent of each map's platforms (or levels, or shops) that have the fact; busiest stations first (calls in the loaded timetable). Columns: **routes** platforms that can be walked to; **levels** platform levels a stair, escalator, lift or ramp reaches; **exits** platforms that reach an entrance; **hours** shops and cafés with opening hours; **sides** platforms whose sides name their tracks; **sectors** platforms with stopping sectors. See \`stationCoverage\` in packages/shared/src/station.ts.`, ''];
  const tierStations = Object.keys(tiers);
  const mapped = new Set(rows.map((r) => r.m.station_id));
  for (const cc of ['SE', 'NO', 'FI', 'DK']) {
    const these = rows.filter((r) => country(r.m.station_id) === cc).sort((a, b) => (busy.get(b.m.station_id) ?? 0) - (busy.get(a.m.station_id) ?? 0));
    if (!these.length) continue;
    const avg = (k: keyof StationCoverage) => pct(these.reduce((s, r) => s + (r.c[k] ?? 0), 0) / these.length);
    const missing = tierStations.filter((id) => country(id) === cc && !mapped.has(id)).length;
    out.push(`## ${cc}: ${these.length} maps${missing ? `, ${missing} hub or mid stations without one` : ''}`, '', `Average: routes ${avg('platforms')}, levels ${avg('vertical')}, exits ${avg('entrances')}, hours ${avg('hours')}, sides ${avg('sides')}.`, '');
    out.push('| Station | Tier | Calls | Platforms | Routes | Levels | Exits | Hours | Sides | Sectors |', '|---|---|---|---|---|---|---|---|---|---|');
    for (const { m, c } of these)
      out.push(`| ${m.name} (\`${m.station_id}\`) | ${tiers[m.station_id]?.tier ?? '–'} | ${busy.get(m.station_id) ?? '–'} | ${m.platforms.length} | ${pct(c.platforms)} | ${pct(c.vertical)} | ${pct(c.entrances)} | ${pct(c.hours)} | ${pct(c.sides)} | ${pct(c.sectors)} |`);
    out.push('');
  }
  fs.writeFileSync(path.join(dir, 'COVERAGE.md'), out.join('\n'));
  console.log(`wrote ${path.join(dir, 'COVERAGE.md')}`);
}
process.exit(bad ? 1 : 0);
