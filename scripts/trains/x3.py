"""Arlanda Express X3 (Alstom Coradia, 4 cars). docs/TRAIN_ART.md; the worked example for the other models.

Sources:
- Owner's side-on photo at speed (older livery; the paint shape is the same), and owner's 3/4 photo of the current
  livery; Wikimedia Commons "X3 Stockholm Central.jpg" (current livery, 3/4).
- sv.wikipedia X3: 4 cars, 93.4 m, axles 2.56 m apart, wheels 0.92 m.
Measured off the side photo (nose tip x=1420 px, roof y=330, underside y=640, 100 px/m):
- doors 365–605 px (0.11–0.89 of body height); door windows 428–548 (0.32–0.71); windows 432–520 (0.33–0.61)
- cab car from the rear: 3 panes, door, 5 panes, wide door (1.43 m, its window right of centre), 3 panes, cab door
- yellow (owner's description of the same photo): a ~0.13 m step where it starts on the roof at 8.65 m, a nearly level
  slope to a knee 0.15 m below the cab door top and 0.45 m behind the door, one straight line to the bottom of the
  front corner (the seam 0.85 m from the tip)
- one low roof cover 11.3–9.5 m. Pantograph not drawn: no source shows which car carries it.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lib import Drawing, main  # noqa: E402

AE = 'arlanda-express'
d = Drawing(car_m=25.0, liveries=[AE])
x, y, M, ROOF, BASE, TIP, REAR = d.x, d.y, d.M, d.ROOF, d.BASE, d.TIP, d.REAR
d.gradient('yellow', ['#ffe24a', '#f6d72f', '#e6c420'], stops=(0, 0.6, 1))

WIN = (0.33, 0.61)
DOOR = (0.11, 0.89)


def door(x0, w, marker=True):
    wide = w > 1.2 * M
    gw = 0.49 if wide else 0.56
    gl = 0.336 if wide else (1 - gw) / 2
    d.door(x0, w, *DOOR, win=(gl, gl + gw, 0.32, 0.71))
    if marker:
        d.paint(f'<rect x="{x0 + 1.5:.1f}" y="{y(0.78):.1f}" width="{w - 3:.1f}" height="{y(0.885) - y(0.78):.1f}" fill="url(#yellow)"/>', AE)


d.roof_box(11.3, 9.5)

# Second car, front end only.
S = d.SECOND_END
d.clip('c2', f'M{d.VB_X - 10},{ROOF} H{S - 4} Q{S},{ROOF} {S},{ROOF + 4} V{BASE} H{d.VB_X - 10} Z')
d.group('c2')
d.add(f'<rect x="{d.VB_X - 10}" y="{ROOF}" width="{S - d.VB_X + 10}" height="{d.H}" fill="url(#body)"/>')
d.add(f'<rect x="{d.VB_X - 10}" y="{ROOF}" width="{S - d.VB_X + 10}" height="5" fill="url(#roof)"/>')
d.windows(S - 4.5 * M, S - 0.35 * M, 3, *WIN)
door(S - 5.6 * M, 0.95 * M)
d.add(f'<rect x="{d.VB_X - 10}" y="{y(0.93):.1f}" width="{S - d.VB_X + 10}" height="{BASE - y(0.93):.1f}" fill="url(#steel)"/>')
d.end()
d.gangway()

# Cab car.
nose = x(2.45)
d.clip(
    'c1',
    f'M{REAR},{BASE} V{ROOF + 4} Q{REAR},{ROOF} {REAR + 4},{ROOF} H{nose - 10:.1f} Q{nose:.1f},{ROOF} {nose + 8:.1f},{ROOF + 6} '
    f'C{x(1.75):.1f},{y(0.12):.1f} {x(0.7):.1f},{y(0.45):.1f} {x(0.15):.1f},{y(0.78):.1f} Q{TIP},{y(0.88):.1f} {TIP},{y(0.95):.1f} L{TIP - 2},{BASE} Z',
)
d.group('c1')
d.add(f'<rect x="{REAR}" y="{ROOF - 4}" width="{TIP - REAR + 10}" height="{d.H + 8}" fill="url(#body)"/>')
d.add(f'<rect x="{REAR}" y="{ROOF}" width="{nose - REAR:.1f}" height="5" fill="url(#roof)"/>')
knee = (x(4.1 + 0.45), y(0.11) + 0.15 * M)
d.paint(
    f'<path d="M{x(8.65):.1f},{ROOF - 4} L{x(8.65):.1f},{ROOF + 0.13 * M:.1f} L{knee[0]:.1f},{knee[1]:.1f} L{x(0.85):.1f},{BASE} L{TIP + 10},{BASE} V{ROOF - 4} Z" fill="url(#yellow)"/>',
    AE,
)
# Black cap over the cab roof and the windscreen down the front slope.
d.add(
    f'<path d="M{x(4.3):.1f},{ROOF - 4} H{TIP + 10} V{y(0.47):.1f} C{x(0.55):.1f},{y(0.40):.1f} {x(1.25):.1f},{y(0.22):.1f} {x(1.85):.1f},{y(0.09):.1f} '
    f'C{x(2.3):.1f},{y(0.03):.1f} {x(3.2):.1f},{ROOF + 3} {x(4.3):.1f},{ROOF + 2} Z" fill="#14181e"/>'
)
d.add(f'<path d="M{x(1.8):.1f},{y(0.13):.1f} C{x(1.3):.1f},{y(0.22):.1f} {x(0.8):.1f},{y(0.33):.1f} {x(0.35):.1f},{y(0.40):.1f}" fill="none" stroke="#ffffff" stroke-opacity="0.18" stroke-width="2.2" stroke-linecap="round"/>')
d.add(f'<path d="M{x(0.85):.1f},{y(0.48):.1f} V{BASE}" stroke="#000" stroke-opacity="0.13" stroke-width="1.2"/>')
d.add(f'<ellipse cx="{x(0.28):.1f}" cy="{y(0.66):.1f}" rx="5" ry="3" fill="#f7f9fb" stroke="#4b4f55" stroke-width="1"/>')
d.windows(REAR + 0.45 * M, x(20.45), 3, *WIN)
door(x(20.25), 0.95 * M)
d.windows(x(19.0), x(10.15), 5, *WIN)
door(x(9.85), 1.43 * M)
d.windows(x(8.1), x(4.5), 3, *WIN)
door(x(4.1), 0.95 * M, marker=False)
d.add(f'<rect x="{REAR}" y="{y(0.93):.1f}" width="{x(2.55) - REAR:.1f}" height="{BASE - y(0.93):.1f}" fill="url(#steel)"/>')
d.end()

# Underframe, bogies (axles 2.56 m, wheels 0.92 m) and the fairing under the nose.
d.add(f'<rect x="{REAR + 40}" y="{BASE}" width="{x(4.0) - REAR - 40:.1f}" height="6" fill="#4b5158"/>')
d.add(f'<rect x="{d.VB_X - 10}" y="{BASE}" width="{S - d.VB_X - 30:.1f}" height="6" fill="#4b5158"/>')
for c in (x(3.7), REAR + 2.6 * M, S - 2.6 * M):
    d.bogie(c, axle_m=2.56, wheel_m=0.92)
d.add(f'<path d="M{x(2.3):.1f},{BASE} H{TIP - 6} Q{TIP - 2},{BASE} {TIP - 6},{BASE + 8} L{x(0.6):.1f},{BASE + 12} H{x(2.3):.1f} Z" fill="#3b4148"/>')

COMMENT = '// Arlanda Express X3, side view to scale. Generated by scripts/trains/x3.py (sources and measurements there); docs/TRAIN_ART.md.'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'apps', 'web', 'src', 'components', 'trains', 'X3.tsx')
if __name__ == '__main__':
    main(d, 'X3Side', COMMENT, OUT)
